"""Regenerate src/data/bus-routes.ts from the uploaded operator list.

Usage: python3 scripts/import-operators.py <path-to-pasted-list>
The pasted list has no line breaks, so records are found by their running number.
"""
import json, re, sys, collections

src = open(sys.argv[1]).read()
body = src.split("Stop-by-Stop Route", 1)[1]

starts, pos = [], 0
for n in range(1, 1000):
    m = re.compile(str(n) + r"(?=[A-Z])").search(body, pos)
    if not m:
        break
    starts.append((n, m.start(), m.end()))
    pos = m.end()

SERV = re.compile(
    r"(DTCA Franchise \([^)]*\)|Non-Franchise \([^)]*\)|State-Owned \([^)]*\)|Diplomatic Zone AC Shuttle|Circular Shuttle)"
)
parsed = []
for i, (n, s, e) in enumerate(starts):
    end = starts[i + 1][1] if i + 1 < len(starts) else len(body)
    segs = [x.strip() for x in body[e:end].strip().split("⇄")]
    m = SERV.search(segs[0])
    parsed.append(dict(n=n, raw=segs[0][: m.start()].strip(), service=m.group(1),
                       cfrom=segs[0][m.end():].strip(), mixed=segs[1], rest=segs[2:]))

known = collections.Counter(s for p in parsed for s in p["rest"])
out = []
for p in parsed:
    mixed, cfrom = p["mixed"], p["cfrom"]
    best = None
    for k in range(1, len(mixed)):
        if not (mixed[k].isupper() and mixed[k - 1] not in " /(-"):
            continue
        a, b = mixed[:k], mixed[k:]
        score = (2 if b in known else 0) + (3 if b.split(" ")[0].lower() == cfrom.split(" ")[0].lower() else 0) + (1 if a in known else 0)
        if best is None or score > best[0]:
            best = (score, k)
    k = best[1]
    stops = [mixed[k:]] + p["rest"]
    # Same name, different place: keep them apart.
    if p["n"] == 102 and stops[0] == "Taltola":
        stops[0] = "Taltola (Khilgaon)"
    stops = ["Konabari (Mirpur)" if s == "Konabari" and "Mazar Road" in stops else s for s in stops]

    raw = p["raw"]
    m = re.match(r"^(.*?)\s*\(([^)]*)\)\s*$", raw)
    operator, line, name_bn = raw, None, None
    if m:
        inner = m.group(2)
        if re.search(r"[\u0980-\u09FF]", inner):
            operator = m.group(1)
            parts = [x.strip() for x in inner.split(" - ", 1)]
            name_bn = parts[0]
            if len(parts) > 1:
                line = parts[1]
        else:
            operator, line = m.group(1), inner
    if operator == "BRTC Pink Bus":
        operator, line = "BRTC", f"Pink Bus {line} · Women only"
    item = {"operator": operator}
    if line: item["line"] = line
    if name_bn: item["nameBn"] = name_bn
    item["service"] = p["service"]
    item["endpoints"] = f"{cfrom} ↔ {mixed[:k]}"
    item["stops"] = stops
    out.append(item)

ts = (
    "// Generated by scripts/import-operators.py from the user's Dhaka city bus operator list.\n"
    "// Do not hand-edit stops here without updating the source list.\n"
    "export type RawBus = {\n  operator: string;\n  line?: string;\n  nameBn?: string;\n  service: string;\n  endpoints: string;\n  stops: string[];\n};\n\n"
    "export const RAW_BUSES: RawBus[] = " + json.dumps(out, ensure_ascii=False, indent=2) + ";\n"
)
open("src/data/bus-routes.ts", "w").write(ts)
print(len(out), "routes;", len({o['operator'] for o in out}), "operators")
